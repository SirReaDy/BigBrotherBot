# PYTHON_ARGCOMPLETE_OK
"""Command-line entrypoint: ``b3 run`` (live) and ``b3 replay`` (offline).

The marker on the first line is argcomplete's: it is what lets *global* completion recognise
``python -m b3.cli`` as completable. The installed `b3` console script is generated by pip rather than
by us, so the marker cannot be put in that file — which is why `b3 completion` recommends per-command
registration, the form that works regardless. See `b3.core.completion`.
"""

from __future__ import annotations

import argparse
import asyncio
import logging
import subprocess
import sys
import time
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from typing import Protocol, runtime_checkable

from b3 import __version__
from b3.config.loader import load_config
from b3.config.schema import Config
from b3.core import completion
from b3.core.instance import RESTART_EXIT_CODE, InstanceSpec
from b3.net.logsource import LogSource
from b3.runtime.bot import Bot, RconClient


@runtime_checkable
class PushClient(RconClient, LogSource, Protocol):
    """A client for an engine that *pushes* its events down the RCON connection.

    Both halves of the bot's input in one object, stated in the type system rather than left as a
    comment: BattlEye and Frostbite have no game log, so their RCON client is also their log source.
    """


def build_bot(
    config: Config,
    *,
    rcon: RconClient | None = None,
    conf_dir: Path | None = None,
    config_path: str = "",
) -> Bot:
    """Build a bot with the plugins listed in the config, loaded in dependency order."""
    from b3.core.plugininstall import installed_plugins_dir, register_installed_plugins
    from b3.core.pluginmgr import load_plugins

    # Git-installed plugins live outside the package tree; make them importable before resolving.
    # This server's own directory is registered last so it lands first on sys.path: if the same
    # plugin exists in both, the copy this server installed for itself wins over the shared pool.
    if config.bot.shared_plugins_dir:
        register_installed_plugins(installed_plugins_dir(config.bot.shared_plugins_dir, conf_dir))
    register_installed_plugins(installed_plugins_dir(config.bot.plugins_dir, conf_dir))

    bot = Bot(config, rcon=rcon)
    # Before the plugins load, not after. A plugin resolving `@conf` in its own settings asks the bot
    # for this path, and a bot that does not know yet falls back to the working directory — so
    # banlist looked for its list files wherever the operator happened to `cd` from, and said it
    # could not read them.
    bot.config_path = Path(config_path) if config_path else None
    for loaded in load_plugins(bot, config, conf_dir=conf_dir):
        bot.add_plugin(loaded.plugin, loaded.name)
    bot.start()
    return bot


#: How often the live loop comes round: fast enough for a local tail and for scheduler ticks.
LIVE_TICK = 0.2

#: Shells `b3 completion` can print a registration for. Every one of these is argcomplete's — this
#: bot writes no completion scripts of its own, which is the whole reason for taking the dependency.
#: PowerShell is on the list because argcomplete 3.x registers a native `ArgumentCompleter` for it;
#: it was not always so, and this project's own notes said Windows had no answer.
SHELLS = ("bash", "zsh", "fish", "tcsh", "powershell")

#: Commands that say nothing about updates when they finish. `update`, `version` and `doctor` each
#: report the same thing themselves and would say it twice; `run` logs it on its own schedule while
#: it runs; `completion` writes a shell snippet somebody pastes, and a stray line in it is a syntax
#: error in their shell rc.
NO_UPDATE_NOTICE = frozenset({"update", "version", "doctor", "completion", "run"})


def _autocomplete(parser: argparse.ArgumentParser) -> None:
    """Let the shell ask this parser what comes next, if argcomplete is installed.

    A no-op otherwise, and silent about it: a bot whose CLI refused to run without a completion
    library would be a poor trade for tab completion.
    """
    try:
        import argcomplete
    except ImportError:
        return
    argcomplete.autocomplete(parser)


def _run_completion(shell: str) -> int:
    """`b3 completion [shell]` — print what to add to a shell so tab completion works.

    Printed rather than installed. Editing somebody's shell configuration behind their back is not
    something a game-server bot should do, and every shell here has its own file with its own
    conventions; one line an operator can read and paste is both smaller and honest.
    """
    guessed = shell or _guess_shell()
    try:
        from argcomplete.shell_integration import shellcode
    except ImportError:
        print("tab completion needs argcomplete, which is an optional extra:")
        print("    pip install 'b3ng[completion]'")
        print("then run this command again.")
        return 1
    if not guessed:
        print(f"name a shell: {', '.join(SHELLS)}")
        return 1
    if guessed not in SHELLS:
        print(f"{guessed}: no completion for that shell. Known: {', '.join(SHELLS)}")
        return 1
    where = {
        "bash": "~/.bashrc",
        "zsh": "~/.zshrc",
        "fish": "~/.config/fish/completions/b3.fish",
        "tcsh": "~/.cshrc",
        "powershell": "your $PROFILE",
    }[guessed]
    print(f"# Add this to {where}, then start a new shell:")
    # argcomplete's own generator, so the mechanics stay its problem and not ours. `use_defaults`
    # off: we ask for exactly the completers this parser declares rather than argcomplete's guesses
    # about files, which would offer every file in the directory for `--game`.
    print(shellcode(["b3"], use_defaults=False, shell=guessed).strip())
    return 0


def _guess_shell() -> str:
    """Which shell asked, from the environment. "" when there is nothing to go on.

    A guess, and the message says so by printing the name it guessed — an operator pasting a bash
    snippet into zsh would otherwise be left wondering why nothing completes.
    """
    import os
    import platform

    if platform.system() == "Windows" and not os.environ.get("SHELL"):
        return "powershell"
    name = Path(os.environ.get("SHELL", "")).name.lower()
    # Git Bash on Windows reports `/bin/bash.exe`, and a guess that fails there fails on the platform
    # least likely to have a shell rc set up already.
    name = name.removesuffix(".exe")
    return name if name in SHELLS else ""


@dataclass(slots=True)
class Connection:
    """How the bot reaches one game server: a way to command it, and a way to hear from it.

    ``shared`` says the two are the same object, which is the case for an engine that pushes its
    events down the RCON socket (BattlEye). Stated as a flag rather than left to an identity check,
    because "is this rcon client also the log source?" is a fact about the *engine*, and reading it
    off `is` invites the reader to think it might be an accident.
    """

    rcon: RconClient
    source: LogSource
    description: str
    shared: bool = False


def _connect(config: Config) -> Connection:
    """Build this game's RCON client and event source.

    For most games these are two independent things: a UDP RCON socket, and a log file (local or
    remote) to tail. A BattlEye game has no log at all — its RCON socket *is* the event stream — so
    there the two are one object, and `server.game_log` is ignored. Deciding that here keeps
    `_run_live` below identical for both, which is the point: the loop should not know.
    """
    from b3.net.logsource import create_log_source
    from b3.net.rcon import Rcon, UdpRconTransport, dialect_for
    from b3.parsers.games import (
        FILE_RCON_FAMILIES,
        PUSH_FAMILIES,
        TCP_RCON_FAMILIES,
        profile_for,
    )

    # Raises UnknownGameError on a typo, which main() reports; nothing has connected yet.
    profile = profile_for(config.server.game)

    if profile.family in FILE_RCON_FAMILIES:
        # A third shape: the events come from a log like most games, but commands are *appended to a
        # file* the game server reads rather than sent over a socket. Altitude has no admin port.
        return Connection(
            rcon=_command_file_client(config),
            source=create_log_source(
                config.server.game_log,
                # utf-8 regardless of `server.encoding`, which defaults to latin-1 for the CoD
                # engines. This log is JSON, and JSON is UTF-8 by definition — reading it as
                # latin-1 does not fail, it just quietly mangles every non-ASCII player name. The
                # source decodes with errors="replace", so a stray byte still costs one character
                # rather than the line.
                encoding="utf-8",
                poll_interval=config.server.log_poll_interval,
                timeout=config.server.log_timeout,
                max_gap=config.server.log_max_gap,
            ),
            description=f"{config.server.game_log} (commands -> {config.server.command_file})",
        )

    if profile.family in PUSH_FAMILIES:
        # An engine that pushes its events: one object is both halves. Which one it is remains the
        # profile's business, not the loop's.
        pushers: dict[str, Callable[[Config], PushClient]] = {
            "battleye": _battleye_client,
            "frostbite": _frostbite_client,
            "homefront": _homefront_client,
            "ravaged": _ravaged_client,
            "frontline": _frontline_client,
        }
        client = pushers[profile.family](config)
        return Connection(
            rcon=client,
            source=client,
            description=(
                f"{config.server.host}:{config.server.port} ({profile.family} rcon, events pushed)"
            ),
            shared=True,
        )

    if profile.family in TCP_RCON_FAMILIES:
        # A fourth shape: events from a log file like most games, but a *stateful* rcon — a TCP
        # session with a login handshake, which cannot be expressed as one of `Rcon`'s dialects
        # because those encode a password into every datagram and this one authenticates once.
        return Connection(
            rcon=_source_client(config),
            source=create_log_source(
                config.server.game_log,
                # utf-8 regardless of `server.encoding`, which defaults to latin-1 for the Call of
                # Duty engines. A Source server writes utf-8, so reading it as latin-1 does not fail
                # — it quietly mangles every non-ASCII player name, and a mangled name is a name no
                # `!ban` will match.
                encoding="utf-8",
                poll_interval=config.server.log_poll_interval,
                timeout=config.server.log_timeout,
                max_gap=config.server.log_max_gap,
            ),
            description=(
                f"{config.server.game_log} (commands -> {config.server.host}:"
                f"{config.server.port} source rcon)"
            ),
        )

    transport = UdpRconTransport(
        config.server.host, config.server.port, timeout=config.server.rcon_timeout
    )
    rcon = Rcon(
        transport,
        password=config.server.rcon_password,
        encoding=config.server.encoding,
        # Black Ops frames its packets differently; every other title speaks plain Quake3.
        dialect=dialect_for(profile.rcon_dialect),
    )
    source = create_log_source(
        config.server.game_log,
        encoding=config.server.encoding,
        poll_interval=config.server.log_poll_interval,
        timeout=config.server.log_timeout,
        max_gap=config.server.log_max_gap,
    )
    return Connection(rcon=rcon, source=source, description=config.server.game_log)


def _command_file_client(config: Config) -> RconClient:
    """The Altitude "rcon": a file the game server reads commands out of.

    Refuses to build without ``server.command_file``. The classic parser died here too, and it is the
    right call: every admin command — every kick, ban and reply — would otherwise be written nowhere
    and report success. A bot that cannot act is not a working bot, and finding out from a player is
    the expensive way.
    """
    from b3.config.schema import ConfigError
    from b3.net.altitude import AltitudeCommandFile

    if not config.server.command_file:
        raise ConfigError(
            f"{config.server.game} is commanded through a file, so server.command_file must be set "
            "(it is the command.txt the game server reads; see `b3 doctor`)"
        )
    client = AltitudeCommandFile(
        config.server.command_file, port=config.server.port, encoding="utf-8"
    )
    client.open()
    return client


def _source_client(config: Config) -> RconClient:
    """Source RCON, opened and authenticated before the bot is handed it.

    Opened here rather than lazily so a wrong password is reported by `b3 run` at startup, next to the
    line that says which server it is, instead of at whatever moment the first command happens to be
    sent — which on a quiet server could be the first `!kick`, hours later.
    """
    from b3.net.source import SourceRconClient

    client = SourceRconClient(
        config.server.host,
        config.server.port,
        config.server.rcon_password,
        timeout=max(config.server.rcon_timeout, 2.0),
        # utf-8 for the same reason the log is read as utf-8: it is what this protocol carries, and
        # `server.encoding` describes the Call of Duty engines rather than this one.
        encoding="utf-8",
    )
    client.open()
    return client


def _battleye_client(config: Config) -> PushClient:
    from b3.net.battleye import BattleyeClient

    return BattleyeClient(
        config.server.host,
        config.server.port,
        config.server.rcon_password,
        timeout=config.server.rcon_timeout,
    )


def _frostbite_client(config: Config) -> PushClient:
    from b3.net.frostbite import FrostbiteClient
    from b3.parsers.frostbite.profiles import ALL as FROSTBITE_PROFILES
    from b3.parsers.frostbite.profiles import LEGACY_MAPLIST

    profile = FROSTBITE_PROFILES.get(config.server.game)
    return FrostbiteClient(
        config.server.host,
        config.server.port,
        config.server.rcon_password,
        timeout=config.server.rcon_timeout,
        # Two per-title things this layer needs. Bad Company 2 and the 2010 Medal of Honor keep a
        # flat map list, where the four Frostbite 2 titles keep (map, gamemode, rounds) entries; the
        # two generations also differ in how fast their chat area can be read (the classic paced
        # Frostbite 1 at 2s and Frostbite 2 at 0.8s), and both follow from this one flag.
        legacy_maplist=config.server.game in LEGACY_MAPLIST,
        # And the verb that moves the game on, which is the last step of loading a named map. Three
        # spellings across the six titles, so it comes from the profile rather than from the flag.
        rotate_command=profile.rotate_command if profile else "",
    )


def _homefront_client(config: Config) -> PushClient:
    from b3.net.homefront import HomefrontClient

    return HomefrontClient(
        config.server.host,
        config.server.port,
        config.server.rcon_password,
        timeout=config.server.rcon_timeout,
    )


def _frontline_client(config: Config) -> PushClient:
    from b3.net.frontline import FrontlineClient

    return FrontlineClient(
        config.server.host,
        config.server.port,
        config.server.rcon_password,
        # This engine authenticates a user as well as a password, and cannot log in without one.
        user=config.server.rcon_user,
        timeout=max(config.server.rcon_timeout, 1.0),
    )


def _ravaged_client(config: Config) -> PushClient:
    from b3.net.ravaged import RavagedClient

    return RavagedClient(
        config.server.host,
        config.server.port,
        config.server.rcon_password,
        # Its `LOGIN=` step names an account too, and a server whose admin is not called "admin"
        # would otherwise be unreachable with no way to say so in the config.
        user=config.server.rcon_user,
        # A longer floor than the rcon default: this engine answers questions, and a player-list
        # round trip on a busy server is not instant.
        timeout=max(config.server.rcon_timeout, 2.0),
    )


def _supervise() -> int:
    """Run the bot in a child process, and start it again when `!restart` stops it.

    `!restart` sets exit code 221 and stops; **it does not re-exec**, and that is deliberate - a
    process that replaces itself in place is how the classic bot leaked file handles and RCON
    sockets. The classic solved the other half by shipping a launcher (`b3/run.py`) that ran the bot
    as a subprocess and started it again on 221, and this is that launcher: one flag rather than a
    second script, so `!restart` works for somebody who is simply running `b3 run` in a terminal.

    Under systemd, Docker or any supervisor, do not use this: `Restart=on-failure` already does it,
    and two things restarting one bot is one too many.

    The child is the same command line minus this flag - taken from `sys.orig_argv`, so it works
    whether the bot was started through the `b3` console script or as `python -m`.
    """
    child = [arg for arg in sys.orig_argv if arg != "--supervise"]
    restarts = 0
    while True:
        status = subprocess.call(child)
        if status != RESTART_EXIT_CODE:
            if restarts:
                logging.info("b3 stopped with exit code %d after %d restart(s)", status, restarts)
            return status
        restarts += 1
        logging.info("b3 asked to restart (%d); starting it again", restarts)


async def _run_live(
    config: Config,
    conf_dir: Path | None = None,
    config_path: str = "",
    *,
    allow_schema_drift: bool = False,
) -> int:
    if not allow_schema_drift and _refuse_on_schema_drift(config, config_path):
        return 1
    connection = _connect(config)
    rcon, source = connection.rcon, connection.source
    # `config_path` is also what `!reconfig` re-reads.
    bot = build_bot(config, rcon=rcon, conf_dir=conf_dir, config_path=config_path)

    from b3.net.logsource import LogSourceError

    try:
        source.open()
    except (OSError, LogSourceError) as exc:
        # The commonest first-run failure of all: a game log that is not where the config says. It
        # used to be a traceback — and because this open sat outside the block below, whatever
        # `_connect` had already built was never closed either.
        logging.error("cannot read %s: %s", connection.description, exc)
        logging.error(
            "-> check server.game_log, then run `b3 -c %s doctor` for the whole picture",
            config_path or "b3.yaml",
        )
        try:
            rcon.close()  # closes the source too on an engine where they are one object
        except Exception:  # noqa: BLE001 - nothing useful to do while giving up
            pass
        return 1

    logging.info("b3 running; reading %s", connection.description)
    # And say so in the game, as the classic bot did from `parser.start()`. On a server whose
    # players know what b3 is, this is how they learn it is watching again after a restart - and
    # after `!restart` it is the only confirmation that the bot came back at all. An operator who
    # would rather it stayed quiet sets `b3_online` to nothing.
    online = bot.messages.get("b3_online", name=config.bot.name, version=__version__)
    if online.strip():
        bot.say(online)
    next_poll = 0.0
    try:
        while bot.exit_code is None:
            now = time.monotonic()
            if now >= next_poll:
                next_poll = now + source.poll_interval
                # Remote sources block on network I/O; keep them off the event loop thread.
                lines = (
                    await asyncio.to_thread(source.read_lines)
                    if source.blocking
                    else source.read_lines()
                )
                for line in lines:
                    await bot.feed_line(line)
            # Timed plugin work (b3.core.scheduler); ticks are deduped to once per second.
            await bot.scheduler.tick()
            await asyncio.sleep(LIVE_TICK)
        # `!die` (0) or `!restart` (221 — the classic code a supervisor script watches for).
        logging.info("stopping with exit code %d", bot.exit_code)
        return bot.exit_code
    finally:
        # Before the socket goes: a pending auth poll would otherwise wake up and query an rcon
        # that has been closed under it.
        bot.auth.cancel_all()
        source.close()
        if not connection.shared:  # on a BattlEye game those were the same socket
            rcon.close()


async def _run_replay(
    config: Config, logfile: str, conf_dir: Path | None = None, config_path: str = ""
) -> None:
    from b3.net.logsource import FileLogSource

    bot = build_bot(config, conf_dir=conf_dir, config_path=config_path)  # no rcon in replay mode
    source = FileLogSource(logfile, encoding=config.server.encoding, from_start=True)
    source.open()
    lines = source.read_lines()
    source.close()
    await bot.replay(lines)
    logging.info("replayed %d lines from %s", len(lines), logfile)


def build_parser() -> argparse.ArgumentParser:
    """Every command, flag and completer the CLI has.

    Built in its own function rather than inside `main` so the shell can be handed the same
    parser an operator gets: a completer attached to the wrong object completes nothing and says
    nothing about it, and the only way to catch that is to ask this parser what it would offer.
    """
    from b3.core.probe import DEFAULT_LINES
    from b3.parsers.games import PROFILES

    parser = argparse.ArgumentParser(prog="b3", description="Big Brother Bot 2.0")
    config_arg = parser.add_argument(
        "-c", "--config", default="b3.yaml", help="path to the YAML config"
    )
    config_arg.completer = completion.configs  # type: ignore[attr-defined]
    parser.add_argument("-v", "--verbose", action="store_true")
    # The first thing anybody types. `b3 version` says more — it also names the latest release — but
    # the flag has to exist, because a tool that answers `--version` with a usage error looks broken.
    parser.add_argument("--version", action="version", version=f"b3 {__version__}")
    sub = parser.add_subparsers(dest="cmd", required=True)
    run = sub.add_parser("run", help="connect to the server and run")
    # An operator who knows their database is fine — a shared one another bot has already upgraded,
    # say — can say so. Named for what it allows rather than for what it disables, so it reads
    # honestly in a systemd unit somebody finds two years from now.
    run.add_argument(
        "--allow-schema-drift",
        action="store_true",
        help="start even when the database has not had this version's migrations",
    )
    run.add_argument(
        "--supervise",
        action="store_true",
        help="start again when `!restart` stops the bot, instead of exiting",
    )

    init = sub.add_parser("init", help="create a bot instance directory for one game server")
    init.add_argument("directory", help="where the instance lives, e.g. /srv/cod4_1/b3")
    init.add_argument("--name", default="b3", help="instance name, used in logs and the unit file")
    # `choices` so a typo is refused here, with the valid set printed, instead of reaching a config
    # file. `metavar` keeps 29 ids out of the usage line; argparse still lists them on an error.
    init.add_argument(
        "--game",
        default="cod4",
        choices=sorted(PROFILES),
        metavar="GAME",
        help="parser id (default: cod4); see `b3 games`",
    )
    init.add_argument("--host", default="127.0.0.1", help="game server address")
    init.add_argument("--port", type=int, default=28960, help="game server RCON port")
    init.add_argument("--rcon-password", default="", help="RCON password")
    init.add_argument("--game-log", default="games_mp.log", help="path or ftp/sftp/http URL")
    init.add_argument(
        "--command-file",
        default="",
        help="altitude only: the file the game server reads commands from "
        "(default: command.txt beside the game log)",
    )
    init.add_argument("--database", default="sqlite:///b3.sqlite", help="SQLAlchemy URL")
    init.add_argument("--shared-plugins-dir", help="plugin pool shared with other instances")
    init.add_argument(
        "--no-geoip",
        action="store_true",
        help="skip the IP-to-country database check; the copy bundled with b3 is used instead",
    )
    init.add_argument("--service", action="store_true", help="also write a systemd unit file")
    init.add_argument("--service-user", default="b3", help="user the systemd unit runs as")
    init.add_argument("--force", action="store_true", help="overwrite an existing config")
    # The default when no --game is given and there is somebody to ask: `b3 init` is the first
    # command a new operator runs, and taking flags they have not read yet is backwards.
    init.add_argument(
        "--interactive",
        action="store_true",
        help="ask the questions instead of taking flags (the default when --game is not given)",
    )
    init.add_argument(
        "--no-interactive",
        dest="interactive",
        action="store_false",
        help="never ask; use the flags and their defaults",
    )
    init.set_defaults(interactive=None)
    sub.add_parser("doctor", help="check this install before starting it for the first time")
    probe = sub.add_parser(
        "probe",
        help="show what this server actually says, and which of our assumptions fit it (read-only)",
    )
    probe.add_argument(
        "--lines",
        type=int,
        default=DEFAULT_LINES,
        help=f"how many log lines to check (default: {DEFAULT_LINES})",
    )
    probe.add_argument(
        "--cvar", default="sv_maxclients", help="which cvar to try reading (default: sv_maxclients)"
    )
    probe.add_argument(
        "--redact",
        action="store_true",
        help="mask addresses and ids, for pasting the output somewhere public",
    )
    comp = sub.add_parser(
        "completion", help="print what to add to your shell so tab completion works"
    )
    # `default=None` rather than `""`: argparse validates a *string* default against `choices`, so an
    # empty default would have to be a choice — and then the shell offers an empty candidate beside
    # the five real ones, which is a thing nobody can type and nobody can read.
    comp.add_argument(
        "shell",
        nargs="?",
        default=None,
        choices=SHELLS,
        metavar="SHELL",
        help=f"one of: {', '.join(SHELLS)} (default: guessed from $SHELL)",
    )

    ver = sub.add_parser("version", help="print this version and the latest released one")
    ver.add_argument(
        "--refresh",
        action="store_true",
        help="ask the remote now instead of using the answer from the last week",
    )

    sub.add_parser("games", help="list the game titles this bot can read")
    sub.add_parser("plugins", help="list every plugin available here, and which this server runs")
