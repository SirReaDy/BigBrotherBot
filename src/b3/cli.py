def main(argv: list[str] | None = None) -> int:
    parser = build_parser()

    # Before parse_args, and only when the shell is asking: argcomplete reads the parser, writes its
    # candidates to file descriptor 8 and exits. With the package absent this is a no-op, which is why
    # it is an optional dependency rather than a requirement — completion is a convenience, and a bot
    # that will not start without it would be a poor trade.
    _autocomplete(parser)
    args = parser.parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )
    try:
        return _dispatch(args)
    finally:
        # After the command, never before it: whatever somebody ran `b3` for is done and printed by
        # now, so a line about a new release cannot delay it or come out in the middle of it.
        _mention_update(args)


def _dispatch(args: argparse.Namespace) -> int:
    """Run the command that was asked for. Split from `main` so the update line comes after it."""
    from b3.config.schema import ConfigError
    from b3.parsers.games import UnknownGameError
    from b3.runtime.bot import MissingServerModError, WrongGameError

    # `init` is the command you run when there is no config yet, `games` is pure reference, and
    # `completion` prints a line for a shell — none of the three must need a config to work. The last
    # one especially: an operator sets up tab completion once, from wherever they happen to be
    # standing, and having it ask for a config file would be the one thing that makes it useless.
    if args.cmd == "init":
        return _run_init(args)
    if args.cmd == "games":
        return _run_games()
    if args.cmd == "completion":
        return _run_completion(args.shell or "")
    # Converting a classic config is what you do *before* there is one to load, so it joins `init`
    # here rather than below. Requiring the file it exists to produce would be a fine joke.
    if args.cmd == "import-config":
        return _run_import_config(args)
    # `version` joins them: "which version am I running" is a question asked *about* an install that
    # is not working, which is the moment its config is least likely to load.
    if args.cmd == "version":
        return _run_version(args.config, args.refresh)

    config = load_config(args.config)
    conf_dir = Path(args.config).resolve().parent  # base for @conf tokens in plugin config paths

    try:
        if args.cmd == "doctor":
            return _run_doctor(config, conf_dir)
        if args.cmd == "probe":
            return _run_probe(config, conf_dir, args.lines, args.cvar, args.redact)
        if args.cmd == "run":
            if args.supervise:
                return _supervise()
            return asyncio.run(
                _run_live(
                    config,
                    conf_dir,
                    args.config,
                    allow_schema_drift=args.allow_schema_drift,
                )
            )
        elif args.cmd == "replay":
            asyncio.run(_run_replay(config, args.logfile, conf_dir, args.config))
        elif args.cmd == "plugins":
            return _run_plugins(config, conf_dir)
        elif args.cmd == "db":
            _run_db(config, args.action, args.revision)
        elif args.cmd == "update":
            return _run_update(config, args.check, args.to, args.yes)
        elif args.cmd == "import-db":
            _run_import(config, args.source_url)
        elif args.cmd == "plugin":
            return _run_plugin(config, args, Path(args.config), conf_dir)
    except (UnknownGameError, ConfigError, MissingServerModError, WrongGameError) as exc:
        # A one-line refusal beats a traceback: these are mistakes in their config, not crashes.
        # A missing server-side mod is the same kind of thing: an install job, with the command to
        # run in the message. `server.game` naming a different title from the one the server is
        # running is the same again, and the fix is one word in the file.
        logging.error("%s", exc)
        return 1
    return 0


def _run_init(args: argparse.Namespace) -> int:
    """`b3 init <dir>` — scaffold one game server's instance directory."""
    directory = Path(args.directory).resolve()
    answers = None
    if _should_ask(args):
        from b3.core import wizard

        try:
            answers = wizard.ask(directory, defaults=_spec_from_flags(args, directory))
        except (EOFError, KeyboardInterrupt):
            # Ctrl-D or Ctrl-C part way through. Nothing has been written yet, which is the whole
            # reason the questions come before the file rather than after each answer.
            print("\nnothing written")
            return 1

    spec = answers.spec if answers is not None else _spec_from_flags(args, directory)
    return _create(args, spec, run_doctor=bool(answers and answers.run_doctor))


def _should_ask(args: argparse.Namespace) -> bool:
    """Whether to ask rather than take the flags.

    `--interactive` and `--no-interactive` are explicit. With neither, asking is the default when no
    `--game` was given *and* there is a terminal to ask at — a scripted `b3 init` with its flags in a
    Dockerfile must never stop and wait for somebody who is not there.
    """
    import sys

    if args.interactive is not None:
        return bool(args.interactive)
    if args.game:
        return False
    return sys.stdin.isatty() and sys.stdout.isatty()


def _spec_from_flags(args: argparse.Namespace, directory: Path) -> InstanceSpec:
    return InstanceSpec(
        directory=directory,
        name=args.name,
        game=args.game or "cod4",
        host=args.host,
        port=args.port,
        rcon_password=args.rcon_password,
        game_log=args.game_log,
        database=args.database,
        shared_plugins_dir=args.shared_plugins_dir,
        command_file=args.command_file,
    )


def _create(args: argparse.Namespace, spec: InstanceSpec, *, run_doctor: bool) -> int:
    import sys

    from b3.core.instance import InstanceError, create_instance

    examples = Path(__file__).resolve().parent.parent.parent / "examples"
    try:
        written = create_instance(
            spec,
            examples_dir=examples if examples.is_dir() else None,
            service=args.service,
            python=sys.executable,
            user=args.service_user,
            force=args.force,
        )
    except InstanceError as exc:
        logging.error("%s", exc)
        return 1

    from b3.core.instance import _needs_command_file

    for path in written:
        print(f"wrote {path}")

    if not args.no_geoip:
        # A copy ships with this bot so geolocation works out of the box; this is what stops it being
        # the copy from whenever the release was cut. Optional, bounded and never fatal — see
        # `b3.core.geoipdata`. Nothing here can stop an instance being created.
        from b3.core.geoipdata import refresh_all

        # Into `~/.b3`, not this instance: every server on this machine reads the same answer about
        # the same addresses, and a copy each would be the same megabytes several times over.
        for said in refresh_all():
            print(said)

    print(f"\nnext:\n  b3 -c {spec.directory / 'b3.yaml'} run")
    if _needs_command_file(spec.game):
        # This family has no rcon password to set, and one path it cannot work without.
        print(f"  (check server.command_file — {spec.game} is driven by writing to that file)")
    elif not spec.rcon_password:
        print("  (set server.rcon_password first — it is empty)")
    if not run_doctor:
        return 0
    # Offered because the config being *written* is not the same as the server being reachable, and
    # the gap between those two is where a first evening goes.
    print()
    from b3.config.loader import load_config

    return _run_doctor(load_config(spec.directory / "b3.yaml"), spec.directory)


def _run_games() -> int:
    """`b3 games` — every valid `server.game`, grouped by the engine that reads it.

    Needs no config on purpose: it answers "what may I write in the config?", which is a question
    asked before there is one.
    """
    from b3.parsers.games import FILE_RCON_FAMILIES, PROFILES, PUSH_FAMILIES, by_family

    grouped = by_family()
    width = max(len(family) for family in grouped)
    for family, titles in grouped.items():
        # What the operator has to configure is the one thing a family decides for them, so it belongs
        # in the listing rather than only in the README: a log to point at, an rcon port that carries
        # the events instead, or a log *and* a command file for an engine with no rcon at all.
        if family in PUSH_FAMILIES:
            source = "events over rcon"
        elif family in FILE_RCON_FAMILIES:
            source = "log + command file"
        else:
            source = "reads a game log"
        print(f"{family:<{width}}  {source:<18}  {'  '.join(titles)}")
    print(f"\n{len(PROFILES)} titles. Set one as `server.game` in the config, or `b3 init --game`.")
    return 0


def _run_plugins(config: Config, conf_dir: Path | None) -> int:
    """`b3 plugins` — the three places a plugin can come from, and what this server runs.

    `b3 plugin list` covers the installed pools only; this is the whole set, which is what an
    operator needs to know what a name in the config may refer to.
    """
    import pkgutil

    import b3.plugins

    from b3.core import plugininstall as pi
    from b3.core.pluginmgr import BUILTIN_PACKAGE

    bundled = sorted(m.name for m in pkgutil.iter_modules(b3.plugins.__path__))
    print(f"bundled ({BUILTIN_PACKAGE}, no install needed):")
    print(f"  {'  '.join(bundled) if bundled else '(none)'}")

    pools = [("this server", pi.installed_plugins_dir(config.bot.plugins_dir, conf_dir))]
    if config.bot.shared_plugins_dir:
        shared = pi.installed_plugins_dir(config.bot.shared_plugins_dir, conf_dir)
        if shared != pools[0][1]:
            pools.append(("shared pool", shared))
    for label, directory in pools:
        records = pi.read_lockfile(directory)
        print(f"\ninstalled, {label} ({directory}):")
        if not records:
            print("  (none)")
        for rec in sorted(records.values(), key=lambda r: r.name):
            print(f"  {rec.name:<20} {rec.version:<10} {rec.ref}")

    print("\nenabled in this config:")
    if not config.plugins:
        print("  (none)")
    for entry in config.plugins:
        note = "  [disabled: loaded but inert]" if entry.disabled else ""
        print(f"  {entry.name:<20} {entry.module or f'{BUILTIN_PACKAGE}.{entry.name}'}{note}")
    return 0


def _run_probe(config: Config, conf_dir: Path | None, lines: int, cvar: str, hide: bool) -> int:
    """`b3 probe` — the raw truth about this server, for pasting back to whoever asked.

    Always exits 0: this reports, it does not judge. `b3 doctor` is the command with a verdict.
    """
    from b3.core.probe import run_probe

    # The checks talk to things, which is chatty, and the report *is* the output here.
    for noisy in ("b3.net.logsource", "b3.net.rcon"):
        logging.getLogger(noisy).setLevel(logging.ERROR)

    for line in run_probe(config, conf_dir, lines=lines, cvar=cvar, hide=hide):
        print(line)
    return 0


def _run_doctor(config: Config, conf_dir: Path | None) -> int:
    """`b3 doctor` — say what is wrong with this install, before it is anyone's evening."""
    from b3.core.doctor import Status, run_checks

    # The checks connect to things, which is chatty. The report is the output here, not the log.
    for noisy in ("alembic", "b3.core.plugininstall", "b3.net.logsource"):
        logging.getLogger(noisy).setLevel(logging.WARNING)

    marks = {Status.OK: "  ok  ", Status.WARN: " warn ", Status.FAIL: " FAIL "}
    checks = run_checks(config, conf_dir, check_update=True)
    width = max(len(c.name) for c in checks)
    for check in checks:
        print(f"[{marks[check.status]}] {check.name:<{width}}  {check.detail}")
        if check.hint and check.status is not Status.OK:
            print(f"{'':>{width + 11}}-> {check.hint}")

    failed = [c for c in checks if c.failed]
    warned = [c for c in checks if c.status is Status.WARN]
    print()
    if failed:
        print(f"{len(failed)} problem(s) to fix before this bot will work properly.")
        return 1
    if warned:
        print(f"ready to run, with {len(warned)} thing(s) worth a look.")
        return 0
    print("everything checks out. Start it with `b3 run`.")
    return 0


def _refuse_on_schema_drift(config: Config, config_path: str) -> bool:
    """True when the bot must not start because the database is behind the code.

    Running half-migrated is worse than refusing: the failure is a column that is not there, which
    surfaces as one feature behaving oddly rather than as anything anybody would connect to an
    upgrade. Every other operator mistake in this project is treated the same way — see the plugin
    loader's fatal-vs-tolerated rule.

    Only *behind* refuses. A database ahead of this code, a database that cannot be reached, and one
    with no stamp at all are all warnings: the first is somebody else's newer bot, the second is
    already reported by everything that touches the database, and the third is a schema built by
    hand, which is unusual but not this command's business to veto.
    """
    from b3.storage import migrate

    state = migrate.schema_state(config.bot.database)
    if state.ahead:
        logging.warning("database %s", state.describe())
        logging.warning(
            "-> a newer bot has migrated this database; this one may quietly stop populating "
            "new columns"
        )
        return False
    if not state.behind:
        return False
    logging.error("database %s", state.describe())
    logging.error("-> run: b3 -c %s db upgrade", config_path or "b3.yaml")
    logging.error("-> or start with --allow-schema-drift if you know this database is fine")
    return True


def _run_db(config: Config, action: str, revision: str) -> None:
    from b3.storage import migrate

    url = config.bot.database
    if action == "upgrade":
        # `command.upgrade` succeeds silently whether it applied five migrations or none, which is
        # indistinguishable from doing nothing — and "did I remember to run it?" is the question.
        result = migrate.upgrade_reporting(url, revision)
        logging.info("database %s", result.describe())
    elif action == "stamp":
        migrate.stamp(url, revision)
        logging.info("database stamped at %s", migrate.current_revision(url))
    elif action == "current":
        logging.info("current revision: %s", migrate.current_revision(url))
    elif action == "head":
        logging.info("head revision: %s", migrate.head_revision(url))


def _run_update(config: Config, check_only: bool, to: str, yes: bool) -> int:
    """`b3 update` — see b3.core.selfupdate for why this exists at all after deleting the classic's.

    Exit codes are chosen for scripting: `--check` answers 1 when an update exists, so a cron job can
    mail its output; anything that went wrong is 2, so "there is an update" and "the check failed"
    cannot be confused by a script.
    """
    import subprocess

    from b3.core import selfupdate

    remote = config.bot.update_remote.strip()
    if not remote:
        print("no update remote is configured (bot.update_remote is empty)")
        return 2
    info = selfupdate.check(remote)
    print(info.describe())
    if info.error:
        return 2
    if check_only:
        return 1 if info.available else 0
    tag = to.strip() or info.latest
    if not tag:
        return 2
    if not to and not info.available:
        print("nothing to install; name a tag with --to to install one anyway")
        return 0
    if selfupdate.in_container():
        # pip in the running environment is the wrong operation here: the image *is* the version.
        print("this is a container — pull a new image rather than updating in place")
        return 2
    command = selfupdate.install_command(remote, tag)
    print(f"installing {tag}: {' '.join(command)}")
    # Said before anything happens, because it is the surprising part: one code install serves every
    # instance on the machine, so this updates all of them at once.
    print("this updates every bot instance using this Python environment")
    if not yes:
        answer = input("go ahead? [y/N] ").strip().lower()
        if answer not in ("y", "yes"):
            print("nothing installed")
            return 0
    result = subprocess.run(command, check=False)
    if result.returncode != 0:
        print(f"pip exited {result.returncode}; nothing has changed in the running bot")
        return 2
    # Never in place: files have changed, and the change takes effect on the next start. And a new
    # version may add a migration, which §4.8's check will refuse to start without.
    print(f"installed {tag}. Restart each bot, then run `b3 -c <config> db upgrade` for each one.")
    return 0


def _update_settings(config_path: str) -> tuple[str, bool]:
    """(remote, may-we-ask) for a command that has no `Config` in its hands.

    `b3 version` and the line printed after a command both run where there may be no config at all —
    or a broken one, since "the config does not parse" is a thing somebody runs `b3 version` to help
    them debug. Either way the answer is the schema's own defaults rather than a traceback.
    """
    from b3.config.schema import BotConfig

    defaults = BotConfig()
    if not Path(config_path).is_file():
        return defaults.update_remote, defaults.update_check
    try:
        config = load_config(config_path)
    except Exception:  # noqa: BLE001 - see the docstring: anything at all here means "the defaults"
        # Broad on purpose, and this is the one place in the CLI where that is right: a YAML syntax
        # error, a schema violation, an unreadable file, a path that is a directory. Whatever it is,
        # the caller is printing a version number or a one-line notice, and neither is worth a
        # traceback about a config that some *other* command will report properly.
        return defaults.update_remote, defaults.update_check
    return config.bot.update_remote, config.bot.update_check


def _run_version(config_path: str, refresh: bool) -> int:
    """`b3 version` — which version this is, and which is the newest published.

    Both, because either alone is half an answer: a number nobody can compare to anything, or a
    release you cannot tell you already have. It exits **0** whatever it finds, unlike
    `b3 update --check`: a command somebody types to read a version number must not fail a script
    that runs it merely because there is a release out.
    """
    from b3.core import selfupdate

    print(f"b3 {__version__}")
    remote, enabled = _update_settings(config_path)
    if not enabled or not remote.strip():
        print("latest release: not checked (update checking is off)")
        return 0
    # Asked at most once a week unless `--refresh` says now, and remembered for whatever asks next.
    info = selfupdate.cached_check(remote, interval=0.0 if refresh else selfupdate.NOTICE_INTERVAL)
    if info.error:
        print(f"latest release: unknown ({info.error})")
        return 0
    print(f"latest release: {info.latest or 'none published yet'}")
    if info.available:
        print(f"run `b3 update` to install {info.latest}")
    return 0


def _mention_update(args: argparse.Namespace) -> None:
    """The line after a command, when a newer release exists. Never in the way of the command.

    Three rules keep this from becoming the thing people mute. It **reads a remembered answer** —
    at most once a week does any command pay for a `git ls-remote`, with a few seconds' timeout, and
    it happens *after* the command has done its work and printed it. It goes to **stderr**, so a
    `b3 games` piped into something else is unaffected. And it says nothing at all unless there is
    an update: being current is not news, and a failed check is not the business of somebody who ran
    `b3 plugins`.

    Only for a terminal. A cron job that wants this asks for it with `b3 update --check`, whose exit
    code is designed for exactly that, and does not want a surprise line in its mail.
    """
    from b3.core import selfupdate

    if args.cmd in NO_UPDATE_NOTICE or not selfupdate.notices_wanted():
        return
    if not sys.stderr.isatty():
        return
    remote, enabled = _update_settings(getattr(args, "config", ""))
    if not enabled or not remote.strip():
        return
    line = selfupdate.notice(selfupdate.cached_check(remote))
    if line:
        print(line, file=sys.stderr)


def _run_plugin(
    config: Config, args: argparse.Namespace, config_path: Path, conf_dir: Path | None
) -> int:
    """`b3 plugin install|list|update|remove` — see b3.core.plugininstall for the policies."""
    from b3.core import plugininstall as pi

    plugins_dir = pi.installed_plugins_dir(config.bot.plugins_dir, conf_dir)
    shared_dir = (
        pi.installed_plugins_dir(config.bot.shared_plugins_dir, conf_dir)
        if config.bot.shared_plugins_dir
        else None
    )
    if getattr(args, "shared", False):
        if shared_dir is None:
            logging.error(
                '--shared needs bot.shared_plugins_dir set in %s (e.g. "@home/plugins")',
                config_path,
            )
            return 1
        plugins_dir = shared_dir
    try:
        if args.plugin_cmd == "install":
            plan = pi.plan_install(args.spec, ref=args.ref)
            print(f"install {plan.url} at {plan.ref} into {plugins_dir}")
            print(
                "note: a plugin runs in-process with full access to your database and server; "
                "only install repositories you trust."
            )
            if not args.yes and not _confirm("proceed?"):
                print("aborted")
                return 1
            record = pi.install(
                args.spec,
                plugins_dir=plugins_dir,
                config_path=config_path,
                conf_dir=conf_dir,
                ref=args.ref,
                enable=not args.no_enable,
                disabled=args.disabled,
                force=args.force,
            )
            print(f"installed {record.name} {record.version} ({record.ref} @ {record.commit[:8]})")
            if args.no_enable:
                print(f"not activated; add it yourself:\n  - name: {record.name}")
                print(f"    module: {record.entry_point}")
            else:
                print(f"activated in {config_path}; restart b3 to load it")
        elif args.plugin_cmd == "enable":
            search = [plugins_dir] if shared_dir is None else [plugins_dir, shared_dir]
            record = pi.enable(
                args.name,
                plugins_dirs=search,
                config_path=config_path,
                conf_dir=conf_dir,
                disabled=args.disabled,
            )
            print(f"enabled {record.name} {record.version} in {config_path}; restart b3 to load it")
        elif args.plugin_cmd == "disable":
            pi.disable(args.name, config_path=config_path)
            print(f"disabled {args.name} in {config_path}; its files were left in place")
        elif args.plugin_cmd == "list":
            pools = [("this server", plugins_dir)]
            if shared_dir is not None and shared_dir != plugins_dir:
                pools.insert(0, ("shared", shared_dir))
            for label, directory in pools:
                records = pi.read_lockfile(directory)
                print(f"[{label}] {directory}")
                if not records:
                    print("  (none)")
                for rec in sorted(records.values(), key=lambda r: r.name):
                    print(
                        f"  {rec.name:<20} {rec.version:<10} {rec.ref:<15} "
                        f"{rec.commit[:8]}  {rec.url}"
                    )
        elif args.plugin_cmd == "update":
            record = pi.update(args.name, plugins_dir=plugins_dir, ref=args.ref, conf_dir=conf_dir)
            print(f"updated {record.name} to {record.version} ({record.ref} @ {record.commit[:8]})")
        elif args.plugin_cmd == "remove":
            pi.remove(
                args.name,
                plugins_dir=plugins_dir,
                config_path=config_path,
                keep_files=args.keep_files,
            )
            print(f"removed {args.name}")
    except pi.PluginInstallError as exc:
        logging.error("%s", exc)
        return 1
    return 0


def _confirm(question: str) -> bool:
    try:
        return input(f"{question} [y/N] ").strip().lower() in ("y", "yes")
    except EOFError:  # non-interactive shell
        return False


def _run_import_config(args: argparse.Namespace) -> int:
    """`b3 import-config` — a classic conf/ directory into this one's YAML, plus what it could not do.

    The report is the feature. Anything unconvertible is named with what to do instead, so the part
    a person still has to do is a finite list rather than an unknown.
    """
    from b3.legacy.config import convert_config_tree

    source = Path(args.source_dir)
    if not source.is_dir():
        logging.error(
            "%s is not a directory; point this at the classic install's conf/ folder", source
        )
        return 1
    report = convert_config_tree(source, Path(args.out), write=not args.dry_run)
    if not report.files:
        logging.error("no b3.xml or plugin_*.ini/.xml found in %s", source)
        return 1
    print(report.render())
    if args.dry_run:
        print("\n(--dry-run: nothing was written)")
    return 0


def _run_import(config: Config, source_url: str) -> None:
    from b3.legacy import import_legacy_database
    from b3.storage.store import SqlAlchemyStorage

    target = SqlAlchemyStorage(config.bot.database)
    report = import_legacy_database(source_url, target)
    target.close()
    logging.info("import complete: %s", report.summary())


